// app/api/ai/analyze/route.ts
import { NextResponse } from "next/server";
import Groq from "groq-sdk";

const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

export async function POST(req: Request) {
  try {
    const { content } = await req.json();

    const chatCompletion = await groq.chat.completions.create({
      messages: [
  {
    role: "system",
    content: `คุณคือผู้เชี่ยวชาญด้านบริหารความเสี่ยงในโรงพยาบาล วิเคราะห์เหตุการณ์และตอบกลับเป็น JSON ภาษาไทย
    
    โดยเลือกเกณฑ์ที่เหมาะสมที่สุดจาก 2 หมวดดังนี้:

    [1. ระดับความรุนแรงทางคลินิก (Clinic)]
    - A: มีโอกาสเกิดความคลาดเคลื่อน แต่ตรวจพบและแก้ไขได้ก่อนเกิดเหตุ
    - B: เกิดความคลาดเคลื่อนแล้ว แต่ตรวจพบก่อนถึงตัวผู้ป่วย
    - C: เกิดกับผู้ป่วย แต่ไม่ทำให้ผู้ป่วยได้รับอันตราย
    - D: เกิดกับผู้ป่วย ต้องเฝ้าระวังเพื่อให้มั่นใจว่าไม่เกิดอันตราย
    - E: เกิดกับผู้ป่วย ส่งผลให้เกิดอันตรายชั่วคราว และต้องรักษา/แก้ไขเพิ่มเติม
    - F: เกิดกับผู้ป่วย ส่งผลให้เกิดอันตรายชั่วคราว ต้องรับไว้ใน รพ. หรือยืดเวลาการรักษานานขึ้น
    - G: เกิดกับผู้ป่วย ส่งผลให้เกิดความเสียหายหรือพิการถาวร
    - H: เกิดกับผู้ป่วย ส่งผลให้เกิดอันตรายถึงขั้นต้องช่วยชีวิต
    - I: เกิดกับผู้ป่วย ส่งผลให้เสียชีวิต
    - Z: ไม่ระบุ

    [2. ระดับความรุนแรงทั่วไป (General)]
    - 1: มีโอกาสเกิดความคลาดเคลื่อนในหน่วยงาน/เกือบพลาด ตรวจพบก่อน
    - 2: เกิดระหว่างหน่วยงาน/ผิดพลาดขึ้นแล้วแต่ตรวจพบก่อน ไม่ส่งผลเสียต่อคนและองค์กร
    - 3: เกิดกับคน/องค์กร ไม่เกิดอันตราย แก้ไขได้ผลน่าพอใจ
    - 4: เกิดกับคน/องค์กร ต้องเฝ้าระวัง/มีผลกระทบทำให้หยุดปฏิบัติงานชั่วคราว
    - 5: ความเสียหายชั่วคราว/มูลค่าไม่เกิน 1,000 บาท/ร้องเรียนภายใน
    - 6: มูลค่าความเสียหาย 1,001-5,000 บาท/บุคคลภายนอกทราบเรื่อง
    - 7: มูลค่าความเสียหาย 5,001-15,000 บาท/กระทบชื่อเสียงภาพลักษณ์องค์กร
    - 8: มูลค่าความเสียหาย 15,001-50,000 บาท/ร้องเรียนผ่านสื่อมวลชน/หน่วยงานราชการ
    - 9: มูลค่าความเสียหาย 50,001 ขึ้นไป/เกิดการฟ้องร้อง
    - 10: ไม่ระบุ

    ตอบกลับเป็น JSON เท่านั้น:
    {
      "summary": "สรุปเหตุการณ์",
      "severityScore": "Low/Medium/High",
      "recommendedClinic": "A-I หรือ Z",
      "clinicDesc": "คำอธิบายเกณฑ์ Clinic ที่เลือก",
      "recommendedGen": "1-10",
      "genDesc": "คำอธิบายเกณฑ์ General ที่เลือก",
      "reason": "เหตุผลที่เลือกวิเคราะห์ระดับนี้"
    }`
  },
  { role: "user", content: content }
],
      model: "llama-3.3-70b-versatile",
      response_format: { type: "json_object" },
    });

    return NextResponse.json(JSON.parse(chatCompletion.choices[0]?.message?.content || "{}"));
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}